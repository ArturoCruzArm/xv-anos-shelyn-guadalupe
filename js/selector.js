const STORAGE_KEY = 'xv_anos_sheilyn_guadalupe_photo_selections';
const LIMITES = {
    ampliacion: null,
    impresion: 200,
    invitacion: null
};
const COSTO_FOTO_ADICIONAL = (window.EVENT_CONFIG && window.EVENT_CONFIG.costoFotoAdicional) || 15;
let photoSelections = {};
